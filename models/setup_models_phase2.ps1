# ---------- helpers ----------

function Download-Zip-Extract($url, $dir) {
    $zip = Join-Path $env:TEMP ((Split-Path $dir -Leaf) + '.zip')
    Invoke-WebRequest -Uri $url -OutFile $zip -UseBasicParsing -Headers $UA
    Expand-Archive -Path $zip -DestinationPath $dir -Force
    Remove-Item $zip -Force
}

function Try-OpenGameArt($name, $pageUrl, $directUrl) {
    $dir = Join-Path $work $name
    if (Test-Path $dir) { return $dir }
    $candidates = @()
    if ($directUrl) { $candidates += $directUrl }
    try {
        $html = (Invoke-WebRequest -Uri $pageUrl -UseBasicParsing -Headers $UA -TimeoutSec 30).Content
        $hits = [regex]::Matches($html, 'https?://opengameart\.org/sites/default/files/[^"<>\s]+\.zip')
        foreach ($h in $hits) { $candidates += $h.Value }
    } catch {}
    foreach ($u in ($candidates | Select-Object -Unique)) {
        try {
            Write-Host "[ downloading ] $name (opengameart) ..." -ForegroundColor Cyan
            Download-Zip-Extract $u $dir
            Write-Host "[done] $name (opengameart)" -ForegroundColor Green
            return $dir
        } catch {}
    }
    return $null
}

function Try-GitHubArchive($name, $repo) {
    $dir = Join-Path $work $name
    if (Test-Path $dir) { return $dir }
    foreach ($branch in @('main','master')) {
        try {
            Write-Host "[ downloading ] $name (github: $repo @$branch) ..." -ForegroundColor Cyan
            Download-Zip-Extract "https://github.com/$repo/archive/refs/heads/$branch.zip" $dir
            Write-Host "[done] $name (github archive)" -ForegroundColor Green
            return $dir
        } catch {}
    }
    return $null
}

function Get-PackModels($packDir) {
    if (-not $packDir) { return @() }
    foreach ($ext in @('*.glb','*.gltf','*.fbx','*.obj')) {
        $found = @(Get-ChildItem -Path $packDir -Recurse -Filter $ext -ErrorAction SilentlyContinue)
        if ($found.Count -gt 0) { return @($found | Sort-Object Name) }
    }
    return @()
}

function Pick-Model($models, $patterns, $exclude) {
    foreach ($pat in $patterns) {
        $hit = $models | Where-Object { $_.Name -like $pat -and ($exclude -notcontains $_.FullName) } |
               Select-Object -First 1
        if ($hit) { return $hit }
    }
    return $null
}

function Convert-GltfToGlb($gltfFile, $outGlb) {
    if (-not $script:hasNode) { return $false }
    Push-Location $gltfFile.DirectoryName
    & npx --yes gltf-pipeline -i $gltfFile.FullName -o $outGlb 2>&1 | Out-Null
    Pop-Location
    return (Test-Path $outGlb)
}

function Convert-FbxToGlb($fbxFile, $outGlb) {
    if (-not $script:hasNode) { return $false }
    Push-Location $fbxFile.DirectoryName
    $out = & npx --yes fbx2gltf -i $fbxFile.FullName -o $outGlb -b 2>&1 | Out-String
    Pop-Location
    if ((Test-Path "$outGlb.glb") -and -not (Test-Path $outGlb)) {
        Move-Item "$outGlb.glb" $outGlb -Force
    }
    if (Test-Path $outGlb) { return $true }
    return $false
}

function Convert-ObjToGlb($objFile, $outGlb) {
    if (-not $script:hasNode) { return $false }
    Push-Location $objFile.DirectoryName
    & npx --yes obj2gltf -i $objFile.FullName -o $outGlb 2>&1 | Out-Null
    Pop-Location
    return (Test-Path $outGlb)
}

